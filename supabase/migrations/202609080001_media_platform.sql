create policy "public can read published live events" on public.live_events for select using (visibility = 'public' and status in ('scheduled', 'live', 'interrupted', 'finished', 'archived'));
create policy "public can read published media" on public.media_assets for select using (visibility = 'public' and published_at is not null);
create policy "public can read active radio programs" on public.radio_programs for select using (active = true);
create policy "public can read active radio schedule" on public.radio_schedule for select using (active = true);

